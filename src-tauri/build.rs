fn main() {
  // 内容资产管线占位资源自愈：真实资产包由 `npm run tauri:build:protected` 生成
  // （content.apack 被 .gitignore 排除，禁止入库），新 clone 缺文件时在此补齐占位，
  // 保证 `tauri build` 不因缺资源而失败；运行时解析失败即管线休眠。
  // 注意：主密钥不再以资源文件随安装包分发（防自动化离线破解），
  // 改由下方 build 时嵌入二进制（XOR 分片混淆）。
  let manifest_dir = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
  let res_dir = manifest_dir.join("resources");
  let _ = std::fs::create_dir_all(&res_dir);
  let apack = res_dir.join("content.apack");
  if !apack.exists() {
    let _ = std::fs::write(
      &apack,
      "PLACEHOLDER: run `npm run tauri:build:protected` to generate the real content pack.\n",
    );
  }

  // 主密钥嵌入：优先环境变量，其次 .security/content_master_key.hex（仓库根）。
  // 生成 OUT_DIR/content_master_key.rs，以 XOR 分片对存储（pad = SHA256(key||域标签)，
  // masked = key ^ pad）——目标是让密钥不以明文字符串形态出现在二进制中，
  // 抬高「读文件即得密钥」的自动化提取门槛；不承诺抵御专业逆向。
  let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
  let key_hex = std::env::var("ALGO_VIZ_CONTENT_MASTER_KEY")
    .ok()
    .map(|v| v.trim().to_string())
    .filter(|v| is_hex64(v))
    .or_else(|| {
      let key_path = manifest_dir
        .parent()
        .map(|p| p.join(".security").join("content_master_key.hex"))?;
      let raw = std::fs::read_to_string(key_path).ok()?;
      let v = raw.trim().to_string();
      if is_hex64(&v) {
        Some(v)
      } else {
        None
      }
    });

  let generated = match key_hex {
    Some(hex) => {
      let key = hex_to_bytes32(&hex).expect("hex64 已校验");
      let pad = sha256_domain(&key, b"algorithm-viz/content-key-shard-v1");
      let masked: Vec<u8> = key.iter().zip(pad.iter()).map(|(k, p)| k ^ p).collect();
      format!(
        "// @generated by build.rs - do not edit\n\
         pub const KEY_PAD: [u8; 32] = {};\n\
         pub const KEY_MASKED: [u8; 32] = {};\n\
         pub fn recombine() -> [u8; 32] {{\n\
         \x20   let mut k = [0u8; 32];\n\
         \x20   for i in 0..32 {{ k[i] = KEY_PAD[i] ^ KEY_MASKED[i]; }}\n\
         \x20   k\n\
         }}\n\
         pub const EMBEDDED_PRESENT: bool = true;\n",
        array_literal(&pad),
        array_literal(&masked),
      )
    }
    None => "// @generated by build.rs - no content master key configured\n\
             pub const EMBEDDED_PRESENT: bool = false;\n\
             pub fn recombine() -> [u8; 32] { [0u8; 32] }\n"
      .to_string(),
  };
  std::fs::write(out_dir.join("content_master_key.rs"), generated)
    .expect("写入 OUT_DIR/content_master_key.rs 失败");

  tauri_build::build()
}

fn is_hex64(s: &str) -> bool {
  s.len() == 64 && s.chars().all(|c| c.is_ascii_hexdigit())
}

fn hex_to_bytes32(hex: &str) -> Option<[u8; 32]> {
  if !is_hex64(hex) {
    return None;
  }
  let mut out = [0u8; 32];
  for i in 0..32 {
    out[i] = u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).ok()?;
  }
  Some(out)
}

fn sha256_domain(key: &[u8; 32], domain: &[u8]) -> [u8; 32] {
  use sha2::{Digest, Sha256};
  let mut hasher = Sha256::new();
  hasher.update(key);
  hasher.update(domain);
  hasher.finalize().into()
}

fn array_literal(bytes: &[u8]) -> String {
  let items: Vec<String> = bytes.iter().map(|b| format!("0x{:02x}u8", b)).collect();
  format!("[{}]", items.join(", "))
}
